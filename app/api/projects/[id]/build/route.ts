import { requireUser } from "@/lib/auth";
import { createServerSupabaseClient } from "@/lib/supabase/server";
import { decryptSecret } from "@/lib/secrets";
import { createGithubRepository, getStoredGithubToken, upsertGithubFile } from "@/lib/github";
import { AIGateway } from "@/ai/gateway";

type GeneratedFile = { path: string; content: string };

function cleanJson(text: string) {
  const t = text.replace(/^```json\s*/i, "").replace(/\s*```$/i, "").trim();
  const m = t.match(/\{[\s\S]*\}/);
  return JSON.parse(m ? m[0] : t);
}
function repoName(name: string) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 80) || "sk-builder-app";
}
function safeFiles(value: unknown) {
  if (!Array.isArray(value)) return [];
  return value.filter((f): f is GeneratedFile =>
    !!f && typeof f.path === "string" && typeof f.content === "string" &&
    !f.path.includes("..") && !f.path.startsWith("/") &&
    f.content.length < 140000 && !f.path.includes(".env")
  ).slice(0, 24);
}

export async function POST(request: Request, context: { params: Promise<{ id: string }> }) {
  try {
    const user = await requireUser();
    const { id } = await context.params;
    const supabase = createServerSupabaseClient();
    const { data: project } = await supabase.from("projects").select("*").eq("id", id).eq("owner_clerk_user_id", user.id).maybeSingle();
    if (!project) return Response.json({ error: "PROJECT_NOT_FOUND" }, { status: 404 });

    const { data: plan } = await supabase.from("project_plans").select("*").eq("project_id", id).order("version", { ascending: false }).limit(1).maybeSingle();
    if (!plan) return Response.json({ error: "PLAN_REQUIRED" }, { status: 400 });

    const { data: connection } = await supabase.from("github_connections").select("encrypted_access_token").eq("clerk_user_id", user.id).maybeSingle();
    if (!connection?.encrypted_access_token) return Response.json({ error: "GITHUB_NOT_CONNECTED" }, { status: 400 });
    const token = await getStoredGithubToken(connection.encrypted_access_token);

    let fullName = project.github_repo_full_name as string | undefined;
    let repoUrl = project.github_repo_url as string | undefined;
    if (!fullName) {
      const created = await createGithubRepository(token, repoName(project.name), project.description || "Generated by SK Builder");
      fullName = created.full_name; repoUrl = created.html_url;
      await supabase.from("projects").update({ github_repo_full_name: fullName, github_repo_url: repoUrl, status: "building", updated_at: new Date().toISOString() }).eq("id", id);
    } else {
      await supabase.from("projects").update({ status: "building", updated_at: new Date().toISOString() }).eq("id", id);
    }

    await supabase.from("project_plans").update({ status: "executing" }).eq("id", plan.id);
    await supabase.from("build_logs").insert({ project_id: id, clerk_user_id: user.id, level: "info", message: "Build started: generating a coherent Next.js application." });

    const { data: providers } = await supabase.from("ai_providers").select("provider,model,priority").eq("clerk_user_id", user.id).eq("enabled", true).order("priority");
    const configured: any[] = [];
    for (const p of providers || []) {
      const k = await supabase.from("ai_api_keys").select("encrypted_secret,enabled").eq("clerk_user_id", user.id).eq("provider", p.provider).maybeSingle();
      if (k.data?.enabled && k.data.encrypted_secret) configured.push({ provider: p.provider, model: p.model || undefined, priority: p.priority, secret: decryptSecret(k.data.encrypted_secret) });
    }
    if (!configured.length) return Response.json({ error: "NO_AI_PROVIDER_CONFIGURED" }, { status: 400 });

    const gateway = new AIGateway(configured);
    const common = `Project: ${project.name}
Description: ${project.description || ""}
Approved plan: ${JSON.stringify(plan)}
Generate production-minded, compile-ready code. Do not use secrets. Do not invent external credentials. Use only dependencies declared in package.json.`;

    const corePrompt = `You are the senior engineer in SK Builder. ${common}
Return ONLY JSON: {"files":[{"path":"...","content":"..."}]}.
Generate the complete application foundation in one coherent pass. Include package.json, tsconfig.json, next-env.d.ts, app/layout.tsx, app/globals.css, app/page.tsx, and the minimum reusable UI/data files needed for the requested product. Use Next.js App Router, TypeScript and Tailwind. The result must run with npm install && npm run build. No markdown fences, no node_modules, no lockfile, no .env.`;
    const core = cleanJson((await gateway.generateText({ userId: user.id, projectId: id, taskType: "code_generation", messages: [{ role: "system", content: "Return JSON only." }, { role: "user", content: corePrompt }], options: { maxTokens: 7000, temperature: 0.1 } })).text);
    const coreFiles = safeFiles(core.files);

    const featurePrompt = `You are the implementation engineer in SK Builder. ${common}
The foundation files will be generated separately. Return ONLY JSON: {"files":[{"path":"...","content":"..."}]}.
Generate the feature files that make the requested product genuinely usable: pages, components, typed domain models, server-safe API route stubs where appropriate, and a README. Do not repeat these foundation paths: package.json, tsconfig.json, next-env.d.ts, app/layout.tsx, app/globals.css, app/page.tsx.
Keep the feature implementation consistent with the approved plan and existing Next.js App Router conventions. If Supabase is required, use environment variables and safe placeholders rather than credentials. No markdown fences.`;
    const features = cleanJson((await gateway.generateText({ userId: user.id, projectId: id, taskType: "code_generation", messages: [{ role: "system", content: "Return JSON only." }, { role: "user", content: featurePrompt }], options: { maxTokens: 7000, temperature: 0.1 } })).text);
    const featureFiles = safeFiles(features.files);

    const merged = [...coreFiles, ...featureFiles].filter((file, index, arr) => arr.findIndex(x => x.path === file.path) === index).slice(0, 24);
    const required = ["package.json", "tsconfig.json", "next-env.d.ts", "app/layout.tsx", "app/globals.css", "app/page.tsx"];
    if (required.some(p => !merged.some(f => f.path === p))) throw new Error("AI_GENERATION_MISSING_FOUNDATION");
    if (merged.length < 8) throw new Error("AI_GENERATION_TOO_SMALL");

    for (const f of merged) {
      await upsertGithubFile(token, fullName, f.path, f.content, `SK Builder: generate ${f.path}`);
      await supabase.from("project_files").upsert({
        project_id: id, path: f.path, content: f.content, content_hash: null,
        status: "generated", updated_at: new Date().toISOString()
      }, { onConflict: "project_id,path" });
    }

    const tasks = Array.isArray(plan.apis) ? plan.apis : [];
    if (tasks.length) {
      await supabase.from("project_tasks").upsert(tasks.slice(0, 30).map((t: any, i: number) => ({
        project_id: id, plan_id: plan.id, task_key: String(t.task_key || `generated-${i + 1}`),
        title: String(t.title || `Implementation task ${i + 1}`),
        description: String(t.description || ""), files: t.files || [], acceptance_criteria: t.acceptance_criteria || [],
        dependencies: t.dependencies || [], priority: Number(t.priority || 100), status: "passed"
      })), { onConflict: "project_id,task_key" });
    }

    await supabase.from("project_plans").update({ status: "completed" }).eq("id", plan.id);
    await supabase.from("projects").update({ status: "ready", updated_at: new Date().toISOString() }).eq("id", id);
    await supabase.from("build_logs").insert({ project_id: id, clerk_user_id: user.id, level: "info", message: `Build completed: ${merged.length} files generated and pushed to GitHub.` });
    return Response.json({ ok: true, repository: { full_name: fullName, url: repoUrl }, files: merged.map(f => f.path) });
  } catch (error) {
    const message = error instanceof Error ? error.message : "BUILD_FAILED";
    try {
      const user = await requireUser(); const { id } = await context.params;
      const s = createServerSupabaseClient();
      await s.from("projects").update({ status: "failed", updated_at: new Date().toISOString() }).eq("id", id).eq("owner_clerk_user_id", user.id);
      await s.from("build_logs").insert({ project_id: id, clerk_user_id: user.id, level: "error", message });
      await s.from("project_plans").update({ status: "failed" }).eq("project_id", id).eq("status", "executing");
    } catch {}
    return Response.json({ error: message }, { status: 500 });
  }
}
