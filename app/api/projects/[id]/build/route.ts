import { requireUser } from "@/lib/auth";
import { createServerSupabaseClient } from "@/lib/supabase/server";
import { decryptSecret } from "@/lib/secrets";
import { createGithubRepository, getStoredGithubToken, upsertGithubFile } from "@/lib/github";
import { AIGateway } from "@/ai/gateway";

type GeneratedFile={path:string;content:string};

function cleanJson(text:string){const t=text.replace(/^\`\`\`json\s*/i,"").replace(/\s*\`\`\`$/i,"").trim();const m=t.match(/\{[\s\S]*\}/);return JSON.parse(m?m[0]:t)}
function repoName(name:string){return name.toLowerCase().replace(/[^a-z0-9]+/g,"-").replace(/^-+|-+$/g,"").slice(0,80)||"sk-builder-app"}

export async function POST(request:Request,context:{params:Promise<{id:string}>}){
  try{
    const user=await requireUser(); const {id}=await context.params; const supabase=createServerSupabaseClient();
    const {data:project}=await supabase.from("projects").select("*").eq("id",id).eq("owner_clerk_user_id",user.id).maybeSingle();
    if(!project)return Response.json({error:"PROJECT_NOT_FOUND"},{status:404});
    const {data:plan}=await supabase.from("project_plans").select("*").eq("project_id",id).order("version",{ascending:false}).limit(1).maybeSingle();
    if(!plan)return Response.json({error:"PLAN_REQUIRED"},{status:400});
    const {data:connection}=await supabase.from("github_connections").select("encrypted_access_token").eq("clerk_user_id",user.id).maybeSingle();
    if(!connection?.encrypted_access_token)return Response.json({error:"GITHUB_NOT_CONNECTED"},{status:400});
    const token=await getStoredGithubToken(connection.encrypted_access_token);
    let fullName=project.github_repo_full_name as string|undefined;
    let repoUrl=project.github_repo_url as string|undefined;
    if(!fullName){
      const created=await createGithubRepository(token,repoName(project.name),project.description||"Generated by SK Builder");
      fullName=created.full_name; repoUrl=created.html_url;
      await supabase.from("projects").update({github_repo_full_name:fullName,github_repo_url:repoUrl,status:"building",updated_at:new Date().toISOString()}).eq("id",id);
    }else{
      await supabase.from("projects").update({status:"building",updated_at:new Date().toISOString()}).eq("id",id);
    }

    const {data:providers}=await supabase.from("ai_providers").select("provider,model,priority").eq("clerk_user_id",user.id).eq("enabled",true).order("priority");
    const configured:any[]=[];
    for(const p of providers||[]){const k=await supabase.from("ai_api_keys").select("encrypted_secret,enabled").eq("clerk_user_id",user.id).eq("provider",p.provider).maybeSingle();if(k.data?.enabled&&k.data.encrypted_secret)configured.push({provider:p.provider,model:p.model||undefined,priority:p.priority,secret:decryptSecret(k.data.encrypted_secret)})}
    if(!configured.length)return Response.json({error:"NO_AI_PROVIDER_CONFIGURED"},{status:400});

    const prompt=`You are SK Builder's senior full-stack engineer. Generate a small but polished, runnable Next.js 16 + TypeScript + Tailwind app from the approved plan below. This is a real starter product, not a mockup. Return ONLY valid JSON: {"files":[{"path":"...","content":"..."}]}. Generate 8-12 files maximum. Include package.json, tsconfig.json, next-env.d.ts, app/globals.css, app/layout.tsx, app/page.tsx and any 2-6 additional files needed for the requested core feature. Do not include node_modules, lockfiles, .env, secrets, or binary files. Use only dependencies listed in package.json. Keep code concise and compile-ready. The home page must clearly implement the requested product, be responsive, accessible, and visually polished. If the plan asks for backend/database features, create typed API stubs or server-safe placeholders rather than inventing credentials. Project name: ${project.name}. Initial idea: ${project.description||""}. Approved plan: ${JSON.stringify(plan)}`;
    const response=await new AIGateway(configured).generateText({userId:user.id,projectId:id,taskType:"code_generation",messages:[{role:"system",content:"Return JSON only. No markdown fences."},{role:"user",content:prompt}],options:{maxTokens:7000,temperature:0.15}});
    const parsed=cleanJson(response.text); const generated=Array.isArray(parsed.files)?parsed.files as GeneratedFile[]:[];
    const safe=generated.filter(f=>f&&typeof f.path==="string"&&typeof f.content==="string"&&!f.path.includes("..")&&!f.path.startsWith("/")&&f.content.length<120000).slice(0,12);
    if(safe.length<6)throw new Error("AI_GENERATION_INVALID");
    for(const f of safe){
      await upsertGithubFile(token,fullName,f.path,f.content,`SK Builder: generate ${f.path}`);
      await supabase.from("project_files").upsert({project_id:id,path:f.path,content:f.content,content_hash:null,status:"generated",updated_at:new Date().toISOString()},{onConflict:"project_id,path"});
    }
    await supabase.from("project_plans").update({status:"completed"}).eq("id",plan.id);
    await supabase.from("projects").update({status:"ready",updated_at:new Date().toISOString()}).eq("id",id);
    return Response.json({ok:true,repository:{full_name:fullName,url:repoUrl},files:safe.map(f=>f.path)});
  }catch(error){
    const message=error instanceof Error?error.message:"BUILD_FAILED";
    return Response.json({error:message},{status:500});
  }
}
